/**
 * The icon stored on a carousel: its offered name, or Film for a missing or
 * unknown one (the server stores whatever string it was sent).
 */
export const getCarouselIcon = (name: string | undefined): LucideIcon =>
  name !== undefined &&
  Object.prototype.hasOwnProperty.call(CAROUSEL_ICON_COMPONENTS, name)
    ? CAROUSEL_ICON_COMPONENTS[name as CarouselIconName]
    : CAROUSEL_ICON_COMPONENTS.Film;
